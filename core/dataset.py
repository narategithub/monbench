#!/usr/bin/env python3
"""dataset.py -- the benchmark data set, independent of any backend.

The data set is split into partitions, one per server node (SERVER_NODES).
Partition p holds components (p + 1) * 1000 + c for c in
[0, components_per_partition), each with one record per sample.

Every attribute's value is a pure function of its identifying coordinates,
computed generically by core/valuegen.py from the dataset's own JSON
definition -- see design/value-generation.md for the design. There is no
hardcoded per-attribute formula here and no fixed, suite-wide attribute
list: a dataset is defined entirely by its JSON file (dataset/default.json
is one example, modeled on the curated_metrics LDMS sampler plugin's flat
metrics), and defining a new one needs no change to this file or to any
backend writer.

Four attributes are identity/time coordinates, not generated metrics, and
every dataset must declare them by these names:

  timestamp     = t0 + seq * interval
  component_id  = given (the caller's identity for this row; this is what
                  design/value-generation.md calls "node_id" -- renaming
                  is a separate, not-yet-done pass, see that doc's Sec 7)
  job_id        = 1 + seq // job_len
  seq           = given

Every other attribute the definition declares is computed by
valuegen.evaluate() -- see that module and design/value-generation.md
Sec 4. A definition may also declare "components" (Sec 6): zero or more
component kinds, each a flat record type with a variable, per-sample
count, generated by valuegen.generate_node_sample(). Dataset exposes this
as expected_components() (every instance's every attribute, for display/
debugging) and, for the verifier's narrower needs, expected_count() and
expected_component_attr() (Sec 6.5's expected_count()/evaluate(attr, C_i),
recomputed directly without generating a kind's whole sample).
core/bench.py's verifier implements Sec 6.5's condition grammar
(kind[i].attr / kind[*].attr / count(kind)) against these, used to filter
the expected *node* row set a query should return. What it does not do is
validate a component kind's own attribute *values* against an
already-returned row, since no backend returns component-kind attributes
as part of a node row -- see each backend's README.md for how it maps a
component kind onto its own schema/measurement instead (Sec 6.5's
backend-mapping table; Stage 5 in STATUS.md).

Every writer, in any backend, must produce exactly these values; the
query engine verifies answers against them.

After a write, the harness records what was written in a metadata file,
<RESULTS_DIR>/meta/<target>.json. The query engine reads it so that it
verifies against the data actually written, and so that it can refuse to
query a target written for a different backend.

Command line (used by bin/node.sh):
  dataset.py meta TARGET WRITER MODE    write the metadata file for TARGET
"""
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import valuegen  # noqa: E402

META_FORMAT = 1

# Every dataset definition must declare these four attributes by name;
# their values are the harness's own sampling/partitioning schedule, not
# a hash-generated metric, so they are computed directly rather than
# through valuegen.evaluate(). See the module docstring.
IDENTITY_ATTRS = ("timestamp", "component_id", "job_id", "seq")


class Dataset:
    def __init__(self, definition, partitions, components, samples, t0,
                 interval, job_len):
        attrs = definition.get("attributes", [])
        names = tuple(a["name"] for a in attrs)
        missing = [a for a in IDENTITY_ATTRS if a not in names]
        if missing:
            raise ValueError(f"data set definition is missing required "
                             f"identity attribute(s) {missing}")
        self.definition = definition
        self.attr_names = names                           # JSON declaration order
        self._attr_by_name = {a["name"]: a for a in attrs}
        self.component_kinds = definition.get("components", [])
        self._component_kind_by_name = {ck["kind"]: ck for ck in self.component_kinds}
        self.partitions = partitions
        self.components_per_partition = components
        self.samples = samples
        self.t0 = t0
        self.interval = interval
        self.job_len = job_len
        self._records = None

    # ------------------------------------------------------------ construction

    @staticmethod
    def load_definition(path):
        with open(path) as f:
            return json.load(f)

    @classmethod
    def from_env(cls, live=False):
        """Parameters from the settings exported by bin/node.sh."""
        e = os.environ
        partitions = len(e["SERVER_NODES"].split())
        return cls(cls.load_definition(e["DATASET"]), partitions,
                   int(e["COMPONENTS_PER_NODE"]),
                   int(e["LIVE_SAMPLES"] if live else e["SAMPLES"]),
                   int(e["T0"]), int(e["INTERVAL"]), int(e["JOB_LEN"]))

    @classmethod
    def from_meta(cls, meta):
        p = meta["params"]
        return cls(meta["dataset"], p["partitions"], p["components_per_partition"],
                   p["samples"], p["t0"], p["interval"], p["job_len"])

    def params(self):
        return {"partitions": self.partitions,
                "components_per_partition": self.components_per_partition,
                "samples": self.samples, "t0": self.t0,
                "interval": self.interval, "job_len": self.job_len}

    # ------------------------------------------------------------ contents

    @property
    def name(self):
        return self.definition["name"]

    def attr_type(self, name):
        return self._attr_by_name[name]["type"]

    def size(self):
        return self.partitions * self.components_per_partition * self.samples

    def components(self, partition=None):
        parts = range(self.partitions) if partition is None else [partition]
        return [(p + 1) * 1000 + c for p in parts
                for c in range(self.components_per_partition)]

    @staticmethod
    def partition_of(component_id):
        return component_id // 1000 - 1

    def expected(self, comp, seq):
        """Every flat attribute's value for (comp, seq), keyed by name."""
        timestamp = float(self.t0 + seq * self.interval)
        job_id = 1 + seq // self.job_len
        values = {"timestamp": timestamp, "component_id": comp,
                 "job_id": job_id, "seq": seq}
        for name in self.attr_names:
            if name in IDENTITY_ATTRS:
                continue
            attr = self._attr_by_name[name]
            values[name] = valuegen.evaluate(attr, self.name, comp, "", 0,
                                             job_id, seq)
        return values

    def expected_components(self, comp, seq):
        """This node's component-kind records for (comp, seq) (Sec 6.3).

        Returns a list of {"kind": ..., "index": ..., <attrs>...} dicts,
        one per component instance. Empty if the definition declares no
        "components". job_id is derived the same way expected() derives
        it, so a caller needing both should prefer calling expected()
        first and deriving job_id from its "job_id" key rather than
        recomputing it, to avoid the two ever disagreeing.
        """
        job_id = 1 + seq // self.job_len
        components = []
        for comp_kind in self.component_kinds:
            n = valuegen.component_count(self.name, comp_kind, comp, job_id, seq)
            kind_name = comp_kind["kind"]
            for c_idx in range(n):
                rec = {"kind": kind_name, "index": c_idx}
                for attr in comp_kind.get("attributes", []):
                    rec[attr["name"]] = valuegen.evaluate(
                        attr, self.name, comp, kind_name, c_idx, job_id, seq)
                components.append(rec)
        return components

    def component_kind(self, kind):
        """The component-kind declaration named *kind*, or None."""
        return self._component_kind_by_name.get(kind)

    @staticmethod
    def _component_attr_def(comp_kind, attr):
        for a in comp_kind.get("attributes", []):
            if a["name"] == attr:
                return a
        raise KeyError(f"component kind {comp_kind['kind']!r} has no attribute {attr!r}")

    def expected_count(self, kind, comp, seq):
        """Expected per-sample count for component kind *kind* (Sec 6.3).

        Recomputes via valuegen.component_count() directly, without
        generating the kind's attribute values -- the cheap primitive
        core/bench.py's verifier needs for a 'count(kind) cmp n' condition
        and for bounds-checking an indexed 'kind[i].attr' condition.
        """
        ck = self.component_kind(kind)
        if ck is None:
            raise KeyError(f"data set {self.name!r} has no component kind {kind!r}")
        job_id = 1 + seq // self.job_len
        return valuegen.component_count(self.name, ck, comp, job_id, seq)

    def expected_component_attr(self, kind, index, attr, comp, seq):
        """One component instance's one attribute value.

        This is Sec 6.5's 'evaluate(attr, C_i)': recomputed directly via
        valuegen.evaluate(), without generating every attribute of every
        instance of this kind the way expected_components() does -- the
        narrower, cheaper call the verifier's indexed/existential
        conditions need. Caller is responsible for checking `index` is
        within range (see expected_count()); this does not bounds-check.
        """
        ck = self.component_kind(kind)
        if ck is None:
            raise KeyError(f"data set {self.name!r} has no component kind {kind!r}")
        attr_def = self._component_attr_def(ck, attr)
        job_id = 1 + seq // self.job_len
        return valuegen.evaluate(attr_def, self.name, comp, kind, index, job_id, seq)

    def component_attr_type(self, kind, attr):
        """The declared type of one component kind's attribute."""
        ck = self.component_kind(kind)
        if ck is None:
            raise KeyError(f"data set {self.name!r} has no component kind {kind!r}")
        return self._component_attr_def(ck, attr)["type"]

    def records(self):
        """Every flat record, as tuples in attr_names order (cached)."""
        if self._records is None:
            self._records = []
            for comp in self.components():
                for seq in range(self.samples):
                    v = self.expected(comp, seq)
                    self._records.append(tuple(v[a] for a in self.attr_names))
        return self._records

    def placeholders(self, limit, literal_formats=None):
        """Values available to query sets as {name}.

        *literal_formats* is an optional dict mapping dataset attribute
        types to format strings (e.g. ``{"timestamp": "to_timestamp({})"}``).
        When provided, placeholder values of that type are wrapped
        accordingly so the generated SQL uses the backend's native literal
        syntax.
        """
        def fmt(val, attr_type):
            if literal_formats and attr_type in literal_formats:
                return literal_formats[attr_type].format(val)
            return val
        def ts(seq):
            return fmt(self.t0 + seq * self.interval, "timestamp")
        s, c, last = self.samples, self.components_per_partition, self.partitions
        mid = s // 2
        return {
            "schema": self.name,
            "limit": limit,
            "t_start": ts(0), "t_end": ts(s - 1),
            "t_q1": ts(s // 4), "t_mid": ts(mid), "t_q3": ts(3 * s // 4),
            "t_mid_1pct": ts(mid + max(1, s // 100)),
            "comp_s0": fmt(1000, "uint64"),
            "comp_s0_last": fmt(1000 + c - 1, "uint64"),
            "comp_slast": fmt(last * 1000, "uint64"),
            "comp_last": fmt(last * 1000 + c - 1, "uint64"),
            "job_first": fmt(1, "uint64"),
            "job_mid": fmt(1 + mid // self.job_len, "uint64"),
            "job_last": fmt(1 + (s - 1) // self.job_len, "uint64"),
        }

# ---------------------------------------------------------------- metadata


def meta_path(target):
    return os.path.join(os.environ["RESULTS_DIR"], "meta", f"{target}.json")


def write_meta(target, writer, mode):
    ds = Dataset.from_env(live=(mode == "live"))
    meta = {
        "format": META_FORMAT,
        "backend": os.environ["BACKEND"],
        "target": target,
        "writer": writer,
        "write_nodes": os.environ["SERVER_NODES"].split(),
        "dataset": ds.definition,
        "params": ds.params(),
        "records": ds.size(),
        "written_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    }
    path = meta_path(target)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(meta, f, indent=2)
    print(f"metadata: {path}")


def read_meta(target):
    path = meta_path(target)
    if not os.path.exists(path):
        return None
    with open(path) as f:
        meta = json.load(f)
    if meta.get("format") != META_FORMAT:
        raise ValueError(f"{path}: unsupported metadata format {meta.get('format')}")
    return meta


def main(argv):
    if len(argv) == 4 and argv[0] == "meta":
        write_meta(*argv[1:])
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
